"""
Result Handler Module

This module handles saving, formatting, and reporting test results.
"""

import os
import json
from pathlib import Path
from datetime import datetime
from typing import Dict, Optional


class ResultHandler:
    """Handles test result saving and reporting"""
    
    def __init__(self, base_dir: Optional[Path] = None):
        """
        Initialize ResultHandler
        
        Args:
            base_dir: Base directory for tests (defaults to tests directory)
        """
        if base_dir is None:
            # Default to tests directory (parent of core)
            base_dir = Path(__file__).parent.parent
        
        self.base_dir = Path(base_dir)
        self.results_dir = self.base_dir / "results"
        self.results_dir.mkdir(exist_ok=True)
        
        # CI environment detection
        self.is_github_actions = os.getenv('GITHUB_ACTIONS', 'false').lower() == 'true'
    
    def _get_status_info(self, result: Dict) -> tuple[str, str]:
        """
        Determine status emoji and text from result
        
        Args:
            result: Test result dictionary
            
        Returns:
            Tuple of (status_emoji, status_text)
        """
        exit_code = result.get('exit_code', 1)
        status = result.get('status', 'unknown')
        
        if status == 'passed' or exit_code == 0:
            return "✅", "PASSED"
        elif status == 'skipped':
            return "⚠️", "SKIPPED"
        else:
            return "❌", "FAILED"
    
    def save_result(self, result: Dict, timestamp: Optional[str] = None) -> Path:
        """
        Save test result to JSON file
        
        Args:
            result: Test result dictionary
            timestamp: Optional timestamp string (generated if not provided)
            
        Returns:
            Path to saved result file
        """
        if timestamp is None:
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        
        result_file = self.results_dir / f"result_{timestamp}.json"
        
        with open(result_file, 'w') as f:
            json.dump(result, f, indent=2)
        
        print(f"\nResult saved to: {result_file}")
        return result_file
    
    def generate_summary(
        self, 
        result: Dict, 
        spec_path: Path,
        category: str,
        timestamp: Optional[str] = None
    ) -> Path:
        """
        Generate test execution summary in Markdown format
        
        Args:
            result: Test result dictionary
            spec_path: Path to test specification
            category: Test category
            timestamp: Optional timestamp string
            
        Returns:
            Path to summary file
        """
        if timestamp is None:
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        
        summary_file = self.results_dir / f"summary_{timestamp}.md"
        
        exit_code = result.get('exit_code', 1)
        status_emoji, status_text = self._get_status_info(result)
        
        # Get username safely for CI environments
        try:
            username = os.getlogin()
        except (OSError, AttributeError):
            username = os.getenv('USER') or os.getenv('USERNAME') or os.getenv('LOGNAME') or 'ci-user'
        
        summary_content = f"""# Test Execution Summary

**Timestamp**: {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}  
**Specification**: {spec_path}  
**Category**: {category}  
**Exit Code**: {exit_code}  
**Status**: {status_emoji} {status_text}

## Execution Details

- **Working Directory**: {self.base_dir}
- **User**: {username}
- **Host**: {os.uname().nodename if hasattr(os, 'uname') else 'unknown'}

## Environment

- **Crawlab API**: {os.getenv('CRAWLAB_API_URL', 'auto-detected')}
- **Test Timeout**: {os.getenv('TEST_TIMEOUT_MINUTES', '30')} minutes

## Results

```json
{json.dumps(result, indent=2)}
```

---
Generated by: Crawlab Test Runner  
Timestamp: {datetime.now().isoformat()}
"""
        
        with open(summary_file, 'w') as f:
            f.write(summary_content)
        
        print(f"Summary saved to: {summary_file}")
        return summary_file
    
    def write_github_actions_summary(
        self, 
        result: Dict,
        spec_path: Path,
        category: str
    ):
        """
        Write summary to GitHub Actions step summary
        
        NOTE: In CI mode, individual test summaries are NOT written to 
        GITHUB_STEP_SUMMARY to avoid verbose output. Instead, test execution 
        results are tracked and a consolidated summary table is generated 
        at the job level in the GitHub Actions workflow.
        
        This method still generates summary files in the results directory
        for artifact upload and debugging purposes.
        
        Args:
            result: Test result dictionary
            spec_path: Path to test specification
            category: Test category
        """
        github_step_summary = os.getenv('GITHUB_STEP_SUMMARY')
        
        if not github_step_summary:
            return
        
        # In CI mode, skip writing individual test summaries to step summary
        # The workflow will generate a consolidated table instead
        if os.getenv('CI', 'false').lower() == 'true':
            print("CI mode: Skipping individual step summary (consolidated summary will be generated)")
            return
        
        exit_code = result.get('exit_code', 1)
        status_emoji, status_text = self._get_status_info(result)
        
        try:
            spec_rel = spec_path.relative_to(self.base_dir)
        except ValueError:
            spec_rel = spec_path
        
        # Extract execution details
        backend = result.get('backend', 'unknown')
        execution_details = result.get('execution_details', {})
        test_report = result.get('test_report', {})
        stdout = result.get('stdout', '').strip()
        stderr = result.get('stderr', '').strip()
        
        # Build execution details section
        details_section = ""
        
        # Add test report summary if available
        if test_report:
            total_steps = test_report.get('total_steps', 0)
            completed_steps = test_report.get('completed_steps', 0)
            failed_steps = test_report.get('failed_steps', 0)
            skipped_steps = test_report.get('skipped_steps', 0)
            
            details_section += f"""
## 📊 Test Execution Summary

| Metric | Value |
|--------|-------|
| **Total Steps** | {total_steps} |
| **Completed** | ✅ {completed_steps} |
| **Failed** | ❌ {failed_steps} |
| **Skipped** | ⚠️ {skipped_steps} |
| **Backend** | `{backend}` |
"""
            
            if test_report.get('reason'):
                details_section += f"\n**Reason**: {test_report.get('reason')}\n"
            
            if test_report.get('duration'):
                details_section += f"\n**Duration**: {test_report.get('duration')}\n"
        
        # Add step details if available
        steps = execution_details.get('steps', [])
        if steps:
            details_section += "\n## 📝 Step Execution Details\n\n"
            for i, step in enumerate(steps[:20], 1):  # Limit to first 20 steps
                status_icon = {
                    'passed': '✅',
                    'failed': '❌',
                    'skipped': '⚠️',
                    'unknown': '❔'
                }.get(step.get('status', 'unknown'), '❔')
                
                step_text = step.get('step', step.get('raw', 'Unknown step'))
                details_section += f"{i}. {status_icon} {step_text}\n"
            
            if len(steps) > 20:
                details_section += f"\n_...and {len(steps) - 20} more steps_\n"
        
        # Add issues/errors if available
        issues = execution_details.get('issues', [])
        if issues:
            details_section += "\n## ⚠️ Issues Detected\n\n"
            for issue in issues[:10]:  # Limit to first 10 issues
                issue_type = issue.get('type', 'unknown').upper()
                issue_msg = issue.get('message', 'No message')
                details_section += f"- **{issue_type}**: {issue_msg}\n"
            
            if len(issues) > 10:
                details_section += f"\n_...and {len(issues) - 10} more issues_\n"
        
        # Add execution logs if available
        logs = execution_details.get('logs', [])
        if logs:
            details_section += "\n## 📋 Execution Logs\n\n<details>\n<summary>Click to expand logs</summary>\n\n```text\n"
            details_section += "\n".join(logs[:100])  # Limit to 100 log lines
            if len(logs) > 100:
                details_section += f"\n\n... ({len(logs) - 100} more log entries) ...\n"
            details_section += "\n```\n\n</details>\n"
        
        # Build the logs section for raw stdout/stderr
        logs_section = ""
        
        if stdout:
            # Truncate very long output
            max_output_chars = 10000
            if len(stdout) > max_output_chars:
                stdout = stdout[:max_output_chars] + f"\n\n... (output truncated, {len(stdout) - max_output_chars} characters omitted) ..."
            
            # Escape HTML to prevent issues with angle brackets
            escaped_stdout = stdout.replace('<', '&lt;').replace('>', '&gt;')
            logs_section += """
## 📋 Raw Output (stdout)

<details>
<summary>Click to expand stdout</summary>

```text
"""
            logs_section += escaped_stdout
            logs_section += """
```

</details>
"""
        
        if stderr:
            # Truncate very long output
            max_output_chars = 5000
            if len(stderr) > max_output_chars:
                stderr = stderr[:max_output_chars] + f"\n\n... (output truncated, {len(stderr) - max_output_chars} characters omitted) ..."
            
            # Escape HTML to prevent issues with angle brackets
            escaped_stderr = stderr.replace('<', '&lt;').replace('>', '&gt;')
            logs_section += """
## ⚠️ Standard Error (stderr)

<details>
<summary>Click to expand stderr</summary>

```text
"""
            logs_section += escaped_stderr
            logs_section += """
```

</details>
"""
        
        github_summary = f"""# {status_emoji} Test Execution: {status_text}

## Test Information

| Attribute | Value |
|-----------|-------|
| **Specification** | `{spec_rel}` |
| **Category** | `{category}` |
| **Status** | {status_emoji} **{status_text}** |
| **Exit Code** | `{exit_code}` |
| **Timestamp** | {datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC")} |
{details_section}
{logs_section}
---
*Generated by Crawlab Test Runner*
"""
        
        try:
            with open(github_step_summary, 'a') as f:
                f.write(github_summary)
            print("GitHub Actions summary written")
        except Exception as e:
            print(f"Warning: Failed to write GitHub Actions summary: {e}")
    
    def log_info(self, message: str):
        """
        Log info message with CI-friendly formatting
        
        Args:
            message: Message to log
        """
        if self.is_github_actions:
            print(f"::notice::{message}")
        else:
            print(f"INFO: {message}")
    
    def log_warning(self, message: str):
        """
        Log warning message with CI-friendly formatting
        
        Args:
            message: Message to log
        """
        if self.is_github_actions:
            print(f"::warning::{message}")
        else:
            print(f"WARNING: {message}")
    
    def log_error(self, message: str):
        """
        Log error message with CI-friendly formatting
        
        Args:
            message: Message to log
        """
        if self.is_github_actions:
            print(f"::error::{message}")
        else:
            print(f"ERROR: {message}")
